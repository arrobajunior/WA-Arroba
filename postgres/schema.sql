-- Schema de transferência v1. Mantém textos/datas e IDs sem normalização.

CREATE TABLE "users" (
  "id" TEXT NOT NULL,
  "name" TEXT NOT NULL,
  "email" TEXT NOT NULL,
  "password_hash" TEXT NOT NULL,
  "role" TEXT NOT NULL,
  "created_at" TEXT NOT NULL,
  "active" BIGINT NOT NULL DEFAULT 1,
  "is_master" BIGINT NOT NULL DEFAULT 0,
  PRIMARY KEY ("id"),
  UNIQUE (email)
);

CREATE TABLE "sessions" (
  "id" TEXT NOT NULL,
  "user_id" TEXT NOT NULL,
  "expires_at" BIGINT NOT NULL,
  PRIMARY KEY ("id"),
  FOREIGN KEY ("user_id") REFERENCES "users" ("id") ON DELETE NO ACTION
);

CREATE TABLE "instances" (
  "id" TEXT NOT NULL,
  "name" TEXT NOT NULL,
  "phone" TEXT NOT NULL DEFAULT '',
  "token" TEXT NOT NULL,
  "settings" TEXT NOT NULL DEFAULT '{}',
  "created_at" TEXT NOT NULL,
  "updated_at" TEXT NOT NULL,
  "owner_id" TEXT,
  "token_encrypted" BIGINT NOT NULL DEFAULT 1,
  "auto_connect" BIGINT NOT NULL DEFAULT 0,
  "webhook_url" TEXT NOT NULL DEFAULT '',
  "active" BIGINT NOT NULL DEFAULT 1,
  "disabled_at" TEXT,
  "disabled_by" TEXT,
  "first_connected_at" TEXT,
  "last_connected_at" TEXT,
  "last_connected_phone" TEXT NOT NULL DEFAULT '',
  PRIMARY KEY ("id"),
  FOREIGN KEY ("owner_id") REFERENCES "users" ("id") ON DELETE NO ACTION
);

CREATE TABLE "messages" (
  "id" TEXT NOT NULL,
  "instance_id" TEXT NOT NULL,
  "recipient" TEXT NOT NULL,
  "body" TEXT NOT NULL,
  "type" TEXT NOT NULL,
  "status" TEXT NOT NULL,
  "ack" TEXT NOT NULL,
  "created_at" TEXT NOT NULL,
  "provider_id" TEXT,
  "error" TEXT,
  "direction" TEXT NOT NULL DEFAULT 'out',
  "priority" BIGINT NOT NULL DEFAULT 10,
  "reference_id" TEXT NOT NULL DEFAULT '',
  "filename" TEXT NOT NULL DEFAULT '',
  "media_id" TEXT,
  "sent_at" BIGINT,
  "queued_at" BIGINT,
  "payload" TEXT NOT NULL DEFAULT '{}',
  "source_url" TEXT NOT NULL DEFAULT '',
  PRIMARY KEY ("id"),
  FOREIGN KEY ("instance_id") REFERENCES "instances" ("id") ON DELETE NO ACTION
);

CREATE TABLE "wa_keys" (
  "instance_id" TEXT NOT NULL,
  "kind" TEXT NOT NULL,
  "key_id" TEXT NOT NULL,
  "value" TEXT NOT NULL,
  PRIMARY KEY ("instance_id", "kind", "key_id"),
  FOREIGN KEY ("instance_id") REFERENCES "instances" ("id") ON DELETE NO ACTION
);

CREATE TABLE "media" (
  "instance_id" TEXT NOT NULL,
  "message_id" TEXT NOT NULL,
  "mimetype" TEXT NOT NULL,
  "data" BYTEA NOT NULL,
  "created_at" TEXT NOT NULL,
  PRIMARY KEY ("instance_id", "message_id"),
  FOREIGN KEY ("instance_id") REFERENCES "instances" ("id") ON DELETE NO ACTION
);

CREATE TABLE "general_settings" (
  "id" BIGINT NOT NULL,
  "alert_email" TEXT NOT NULL DEFAULT '',
  "updated_at" TEXT,
  "updated_by" TEXT,
  PRIMARY KEY ("id"),
  CHECK (id=1)
);

CREATE TABLE "admin_audit" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  "created_at" TEXT NOT NULL,
  "actor_id" TEXT NOT NULL,
  "actor_name" TEXT NOT NULL,
  "actor_email" TEXT NOT NULL,
  "action" TEXT NOT NULL,
  "before_value" TEXT NOT NULL,
  "after_value" TEXT NOT NULL,
  PRIMARY KEY ("id")
);

CREATE TABLE "connection_incidents" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  "instance_id" TEXT NOT NULL,
  "opened_at" TEXT NOT NULL,
  "reason" TEXT NOT NULL,
  "resolved_at" TEXT,
  "notification_status" TEXT NOT NULL DEFAULT 'pending',
  "attempts" BIGINT NOT NULL DEFAULT 0,
  "next_attempt_at" BIGINT NOT NULL DEFAULT 0,
  "recipient" TEXT NOT NULL DEFAULT '',
  "message_id" TEXT NOT NULL DEFAULT '',
  "last_error" TEXT NOT NULL DEFAULT '',
  "instance_name" TEXT NOT NULL DEFAULT '',
  "instance_phone" TEXT NOT NULL DEFAULT '',
  "owner_name" TEXT NOT NULL DEFAULT '',
  "source" TEXT NOT NULL DEFAULT 'unknown',
  "disconnect_code" BIGINT,
  "last_event_at" TEXT,
  "reconnect_attempts" BIGINT NOT NULL DEFAULT 0,
  "last_connected_at" TEXT,
  "email_sent_at" TEXT,
  "capture_version" TEXT NOT NULL DEFAULT 'legacy',
  "deployment_id" TEXT NOT NULL DEFAULT '',
  "app_commit" TEXT NOT NULL DEFAULT '',
  "outage_kind" TEXT NOT NULL DEFAULT 'confirmed',
  "resolution_reason" TEXT NOT NULL DEFAULT '',
  PRIMARY KEY ("id"),
  FOREIGN KEY ("instance_id") REFERENCES "instances" ("id") ON DELETE NO ACTION
);

CREATE TABLE "connection_incident_events" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  "incident_id" BIGINT NOT NULL,
  "created_at" TEXT NOT NULL,
  "kind" TEXT NOT NULL,
  "details" TEXT NOT NULL DEFAULT '{}',
  PRIMARY KEY ("id"),
  FOREIGN KEY ("incident_id") REFERENCES "connection_incidents" ("id") ON DELETE NO ACTION
);

CREATE TABLE "connection_candidates" (
  "instance_id" TEXT NOT NULL,
  "opened_at" TEXT NOT NULL,
  "due_at" BIGINT NOT NULL,
  "reason" TEXT NOT NULL,
  "metadata" TEXT NOT NULL,
  "snapshot" TEXT NOT NULL,
  "events" TEXT NOT NULL DEFAULT '[]',
  "reconnect_attempts" BIGINT NOT NULL DEFAULT 0,
  PRIMARY KEY ("instance_id"),
  FOREIGN KEY ("instance_id") REFERENCES "instances" ("id") ON DELETE NO ACTION
);

CREATE TABLE "schema_migrations" (
  "name" TEXT NOT NULL,
  PRIMARY KEY ("name")
);

CREATE TABLE "instance_activity" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  "created_at" TEXT NOT NULL,
  "instance_id" TEXT,
  "instance_name" TEXT NOT NULL DEFAULT '',
  "actor_id" TEXT NOT NULL DEFAULT '',
  "actor_name" TEXT NOT NULL,
  "actor_email" TEXT NOT NULL DEFAULT '',
  "actor_role" TEXT NOT NULL DEFAULT '',
  "actor_kind" TEXT NOT NULL,
  "action" TEXT NOT NULL,
  "outcome" TEXT NOT NULL,
  "source" TEXT NOT NULL,
  "request_id" TEXT NOT NULL DEFAULT '',
  "before_value" TEXT NOT NULL DEFAULT '{}',
  "after_value" TEXT NOT NULL DEFAULT '{}',
  "details" TEXT NOT NULL DEFAULT '{}',
  "peer_ip" TEXT NOT NULL DEFAULT '',
  "legacy_key" TEXT,
  PRIMARY KEY ("id"),
  UNIQUE (legacy_key)
);

CREATE TABLE "media_objects" (
  "instance_id" TEXT NOT NULL,
  "message_id" TEXT NOT NULL,
  "object_key" TEXT NOT NULL,
  "mimetype" TEXT NOT NULL,
  "size" BIGINT NOT NULL,
  "created_at" TEXT NOT NULL,
  PRIMARY KEY ("instance_id", "message_id"),
  FOREIGN KEY ("instance_id") REFERENCES "instances" ("id") ON DELETE NO ACTION
);

CREATE TABLE "api_messages" (
  "api_id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  "message_id" TEXT NOT NULL,
  PRIMARY KEY ("api_id"),
  FOREIGN KEY ("message_id") REFERENCES "messages" ("id") ON DELETE CASCADE,
  UNIQUE (message_id)
);

CREATE TABLE "branding" (
  "id" BIGINT NOT NULL,
  "name" TEXT NOT NULL,
  PRIMARY KEY ("id"),
  CHECK (id=1)
);

CREATE TABLE "brand_assets" (
  "slot" TEXT NOT NULL,
  "data" BYTEA NOT NULL,
  "revision" TEXT NOT NULL,
  PRIMARY KEY ("slot")
);

CREATE INDEX messages_instance_created ON messages(instance_id,created_at);

CREATE INDEX messages_instance_provider ON messages(instance_id,provider_id);
CREATE INDEX messages_instance_status ON messages(instance_id,status);
CREATE INDEX messages_pending_priority ON messages(instance_id,priority,created_at,id) WHERE status='queue';

CREATE INDEX media_created ON media(created_at);

CREATE UNIQUE INDEX connection_incident_open ON connection_incidents(instance_id) WHERE resolved_at IS NULL;

CREATE INDEX connection_incident_pending ON connection_incidents(notification_status,next_attempt_at);

CREATE INDEX connection_incident_time ON connection_incidents(opened_at,id);

CREATE INDEX connection_incident_event_order ON connection_incident_events(incident_id,id);

CREATE INDEX connection_candidates_due ON connection_candidates(due_at);

CREATE INDEX instance_activity_time ON instance_activity(created_at,id);

CREATE INDEX instance_activity_instance ON instance_activity(instance_id,id);

CREATE INDEX instance_activity_actor ON instance_activity(actor_id,id);

CREATE UNIQUE INDEX users_single_master ON users(is_master) WHERE is_master=1;

CREATE INDEX instances_owner ON instances(owner_id);

CREATE INDEX sessions_expiry ON sessions(expires_at);
